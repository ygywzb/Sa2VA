import warnings

warnings.filterwarnings("ignore", category=RuntimeWarning)
import argparse
import json
import multiprocessing as mp
import os.path as osp
import pickle
import queue
import time

import numpy as np
from pycocotools import mask as cocomask

from third_parts.revos.utils.metircs import db_eval_boundary, db_eval_iou

NUM_WORKERS = 128

exp_dict = None
mask_dict = None
mask_pred_dict = None


def build_meta_with_anno_ids(exp_path):
    with open(exp_path, 'r') as f:
        subset_expressions_by_video = json.load(f)['videos']

    videos = sorted(list(subset_expressions_by_video.keys()))
    anno_count = 0
    for vid in videos:
        vid_data = subset_expressions_by_video[vid]
        exp_id_list = sorted(list(vid_data['expressions'].keys()), key=lambda x: int(x))
        for exp_id in exp_id_list:
            subset_expressions_by_video[vid]['expressions'][exp_id]['anno_id'] = [anno_count]
            anno_count += 1

    return subset_expressions_by_video


def eval_queue(task_queue, out_dict):
    while True:
        try:
            vid_name, exp = task_queue.get_nowait()
        except queue.Empty:
            break

        vid = exp_dict[vid_name]
        exp_name = f'{vid_name}_{exp}'
        pred = mask_pred_dict[vid_name][exp]

        h, w = pred['prediction_masks'][0]['size']
        vid_len = len(vid['frames'])
        gt_masks = np.zeros((vid_len, h, w), dtype=np.uint8)
        pred_masks = np.zeros((vid_len, h, w), dtype=np.uint8)

        anno_ids = vid['expressions'][exp]['anno_id']

        for frame_idx in range(vid_len):
            for anno_id in anno_ids:
                mask_rle = mask_dict[str(anno_id)][frame_idx]
                if mask_rle:
                    gt_masks[frame_idx] += cocomask.decode(mask_rle)

            pred_mask = cocomask.decode(pred['prediction_masks'][frame_idx])
            pred_masks[frame_idx] += pred_mask

        j = db_eval_iou(gt_masks, pred_masks).mean()
        f = db_eval_boundary(gt_masks, pred_masks).mean()
        out_dict[exp_name] = [j, f]


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Evaluate REFYTVOS (RVOS) with J/F/J&F metrics.')
    parser.add_argument('pred_path', type=str, help='Path to results.json generated by sa2va_eval_ref_vos.py')
    parser.add_argument(
        '--exp_path',
        type=str,
        default='data/video_datas/rvos/meta_expressions/valid/meta_expressions.json',
        help='Path to REFYTVOS meta_expressions json',
    )
    parser.add_argument(
        '--mask_path',
        type=str,
        default='data/video_datas/rvos/mask_dict.pkl',
        help='Path to REFYTVOS mask dict (pkl or json)',
    )
    parser.add_argument('--save_name', type=str, default='refytvos_valid.json')
    parser.add_argument('--num_workers', type=int, default=NUM_WORKERS)
    args = parser.parse_args()

    task_queue = mp.Queue()

    exp_dict = build_meta_with_anno_ids(args.exp_path)
    if args.mask_path.endswith('json'):
        mask_dict = json.load(open(args.mask_path))
    elif args.mask_path.endswith('pkl'):
        mask_dict = pickle.load(open(args.mask_path, 'rb'))
    else:
        raise NotImplementedError('mask_path must end with .pkl or .json')

    mask_pred = json.load(open(args.pred_path))

    exp_dict = mp.Manager().dict(exp_dict)
    mask_dict = mp.Manager().dict(mask_dict)
    mask_pred_dict = mp.Manager().dict(mask_pred)
    output_dict = mp.Manager().dict()

    for vid_name in exp_dict:
        vid = exp_dict[vid_name]
        for exp in vid['expressions']:
            task_queue.put([vid_name, exp])

    start_time = time.time()
    if args.num_workers > 1:
        processes = []
        for _ in range(args.num_workers):
            p = mp.Process(target=eval_queue, args=(task_queue, output_dict))
            p.start()
            processes.append(p)

        for p in processes:
            p.join()
    else:
        eval_queue(task_queue, output_dict)

    j = [output_dict[x][0] for x in output_dict]
    f = [output_dict[x][1] for x in output_dict]

    output_path = osp.join(osp.dirname(args.pred_path), args.save_name)
    results = {
        'J': round(100 * float(np.mean(j)), 2),
        'F': round(100 * float(np.mean(f)), 2),
        'J&F': round(100 * float((np.mean(j) + np.mean(f)) / 2), 2),
    }

    with open(output_path, 'w') as f:
        json.dump(results, f, indent=4)

    print(json.dumps(results, indent=4))
    print(f'Results saved to {output_path}')

    end_time = time.time()
    print('time: %.4f s' % (end_time - start_time))